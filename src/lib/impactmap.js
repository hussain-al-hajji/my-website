/** إسقاط خط العرض والطول على مساحة الخريطة 1000×600 */
export const P = (lat, lon) => [((lon - 35) / (60 - 35)) * 1000, ((31 - lat) / (31 - 15.8)) * 600];

/** عدد المشاركات لكل مدينة، بنفس قواعد الرئيسية: الحضوري بلا مدينة يُحتسب في الرياض */
export function cityCounts(records) {
  const counts = {};
  records.forEach((r) => {
    const txt = `${r.location || ''} ${r.org || ''} ${r.title || ''}`;
    let hit = false;
    CITIES.forEach((c) => { if (c[1].some((k) => txt.includes(k))) { counts[c[0]] = (counts[c[0]] || 0) + 1; hit = true; } });
    if (!hit && !/عن بُعد/.test(r.kind || '')) counts['الرياض'] = (counts['الرياض'] || 0) + 1;
  });
  return counts;
}

/** عناصر الخريطة جاهزة للرسم: أقواس من الأحساء، ودوائر بحجم المشاركات، وأسماء المدن الكبيرة */
export function mapShapes(records) {
  const counts = cityCounts(records);
  const home = P(25.38, 49.59);
  const POS = { 'الأحساء': 'd', 'الدمام والخبر': 'u', 'الإمارات': 'r', 'قطر': 'r', 'البحرين': 'u', 'المدينة المنورة': 'u' };
  const placed = CITIES.filter((c) => counts[c[0]]).map((c) => {
    const [x, y] = P(c[2], c[3]), n = counts[c[0]], isHome = c[0] === 'الأحساء', rad = 4 + Math.sqrt(n) * 2.4;
    let arc = '';
    if (!isHome) {
      const mx = (home[0] + x) / 2, my = (home[1] + y) / 2, dx = x - home[0], dy = y - home[1], len = Math.hypot(dx, dy);
      arc = `M${home[0]},${home[1]} Q${mx - dy * 0.22},${my + dx * 0.22 - len * 0.12} ${x},${y}`;
    }
    let label = null;
    if (n >= 3 || isHome) {
      const pos = POS[c[0]] || (x < 110 ? 'r' : 'l');
      let lx = x, ly = y + 5, an = 'middle';
      if (pos === 'l') { lx = x - rad - 8; an = 'start'; } else if (pos === 'r') { lx = x + rad + 8; an = 'end'; } else if (pos === 'u') { ly = y - rad - 30; } else { ly = y + rad + 20; }
      label = { x: lx, y: ly, anchor: an };
    }
    return { name: c[0], n, x, y, rad, isHome, arc, label };
  });
  return { placed, total: placed.length, label: `تم تنفيذ البرامج حضورياً في أكثر من ${Math.floor(placed.length / 10) * 10} موقعاً داخل وخارج المملكة` };
}
